CREATE TABLE approval_package (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT NOT NULL,
 week_start DATE NOT NULL,
 work_item_id BIGINT NOT NULL,
 approver_user_id BIGINT NOT NULL,
 default_approver_id BIGINT NULL,
 route_reason VARCHAR(500) NOT NULL,
 submit_deadline DATETIME(6) NOT NULL,
 approval_deadline DATETIME(6) NOT NULL,
 config_version_id VARCHAR(64) NOT NULL,
 row_version INT NOT NULL DEFAULT 0,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uk_approval_package (user_id,week_start,work_item_id),
 KEY idx_package_pending (approver_user_id,approval_deadline),
 FOREIGN KEY (user_id) REFERENCES app_user(id),
 FOREIGN KEY (work_item_id) REFERENCES work_item(id),
 FOREIGN KEY (approver_user_id) REFERENCES app_user(id),
 FOREIGN KEY (default_approver_id) REFERENCES app_user(id),
 CHECK (user_id<>approver_user_id),
 CHECK (WEEKDAY(week_start)=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE approval_item (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 package_id BIGINT NOT NULL,
 time_revision_id BIGINT NULL,
 onsite_revision_id BIGINT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 submitted_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 submit_deadline DATETIME(6) NOT NULL,
 approval_deadline DATETIME(6) NOT NULL,
 handled_by BIGINT NULL,
 handled_at DATETIME(6) NULL,
 reason VARCHAR(1000) NOT NULL DEFAULT '',
 UNIQUE KEY uk_approval_time_version (time_revision_id),
 UNIQUE KEY uk_approval_onsite_version (onsite_revision_id),
 KEY idx_approval_pending (package_id,status),
 FOREIGN KEY (package_id) REFERENCES approval_package(id),
 FOREIGN KEY (time_revision_id) REFERENCES time_entry_revision(id),
 FOREIGN KEY (onsite_revision_id) REFERENCES onsite_day_revision(id),
 FOREIGN KEY (handled_by) REFERENCES app_user(id),
 CHECK ((time_revision_id IS NULL)<>(onsite_revision_id IS NULL)),
 CHECK (status IN ('PENDING','APPROVED','REJECTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
