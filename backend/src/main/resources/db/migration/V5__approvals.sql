 approval_item_id BIGINT NOT NULL,
 opened_by BIGINT NOT NULL,
 approver_user_id BIGINT NOT NULL,
 employee_statement TEXT NOT NULL,
 approver_statement TEXT NOT NULL,
 original_statement TEXT NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'OPEN',
 stage VARCHAR(20) NOT NULL DEFAULT 'COORDINATION',
 coordinator_id BIGINT NOT NULL,
 owner_department_id BIGINT NOT NULL,
 outcome VARCHAR(30) NULL,
 resolution_reason VARCHAR(1000) NULL,
 resolved_by BIGINT NULL,
 resolved_at DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 KEY idx_dispute_item (approval_item_id,state),
 KEY idx_dispute_coordinator (coordinator_id,state),
 FOREIGN KEY (approval_item_id) REFERENCES approval_item(id),
 FOREIGN KEY (opened_by) REFERENCES app_user(id),
